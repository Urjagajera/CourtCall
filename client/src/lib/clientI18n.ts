export const CLIENT_TEXT: Record<Lang, ClientStrings> = { en, hi, gu }

export const ClientLangContext = createContext<Lang>('en')
export const useClientText = () => CLIENT_TEXT[useContext(ClientLangContext)]
export const useClientLang = () => LANGS.find((l) => l.code === useContext(ClientLangContext))!

export function agoIn(t: ClientStrings, iso: string, now: number) {
  const s = Math.max(0, Math.round((now - new Date(iso).getTime()) / 1000))
  if (s < 45) return t.justNow
  const m = Math.round(s / 60)
  if (m < 60) return t.minAgo(m)
  return t.hAgo(Math.floor(m / 60), m % 60)
}

export function dateIn(lang: Lang, iso: string) {
  const [y, mo, d] = iso.split('-').map(Number)
  const locale = LANGS.find((l) => l.code === lang)!.locale
  return new Date(y, mo - 1, d).toLocaleDateString(locale, { weekday: 'short', day: 'numeric', month: 'short' })
}
